// 웹 suitModel 을 바탕으로 부위(머리 · 몸통 · 팔 · 다리)를 갈아 끼운다 — 웹 대조(ModelParityTests)는 웹 머리 이름만 쓰므로 영향 없다.
// 감독 요청: 실제 게임 픽셀 크기에서 기존 적 누구와도 헷갈리지 않게 — 머리 모양(모자 · 헬멧) · 어깨 폭 · 키 · 색 · 소품을 모두 다르게.
