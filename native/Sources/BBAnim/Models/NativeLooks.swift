//               (빨간 반다나 + 검은 양복인 칼잡이와 갈리게 몸은 어떤 적도 안 쓰는 보라)
//   라인배커   = 금색 헬멧(파란 줄 · 철망 얼굴 가리개) · 넓은 어깨 보호대 · 파란 저지(흰 등번호 · 소매 줄) · 금색 바지 · 파란 긴 양말 · 몸 1.08배
//   신문팔이   = 밝은 황갈색 체크 뉴스보이 캡(불룩한 정수리 · 짧은 챙) · 흰 셔츠 · 갈색 조끼 · 멜빵 · 반바지(니커보커) · 긴 양말 · 신문 가방 · 신문 묶음 · 몸 0.8배

public enum NativeLooks {
    /// 네이티브 머리 이름(LookSpec.hair)
    public static let hairs: Set<String> = ["nv_spar", "nv_lineback", "nv_newsboy"]

    /// 몸 크기 배율(리그 · 모델을 같이 키우거나 줄인다 — 발 위치는 그대로). 없으면 nil
    public static func scale(hair: String?) -> Double? {
        switch hair {
        case "nv_lineback": return 1.08
        case "nv_newsboy": return 0.8
        default: return nil
        }
    }
    /// 생김새 열쇠(hair|fat|coat|boss|tie|mandarin)로 몸 크기 배율
    public static func scale(lookKey: String) -> Double? { LookSpec(key: lookKey).flatMap { scale(hair: $0.hair) } }

    /// 네이티브 생김새 모델(모르는 머리면 nil → 웹 defFor 모델)
    public static func model(_ L: LookSpec) -> Model3? {
        switch L.hair {
        case "nv_spar": return spar()
        case "nv_lineback": return lineback()
        case "nv_newsboy": return newsboy()
        default: return nil
        }
    }

    // MARK: 크기 바꾸기

    /// 리그 치수를 k 배(관절 위치 · 팔다리 길이 · 자세 오프셋 배율 sc)
    public static func scaled(_ R: RigDims, _ k: Double) -> RigDims {
        var r = R
        r.hip *= k; r.head = r.head * k; r.shF = r.shF * k; r.shB = r.shB * k; r.legF = r.legF * k; r.legB = r.legB * k
        r.upper *= k; r.fore *= k; r.armLenF *= k; r.armLenB *= k
        r.thigh = (R.thigh ?? 6) * k; r.shin = (R.shin ?? 7) * k
        r.sc = (R.sc ?? 1) * k
        return r
    }
    /// 모델 조각을 k 배(뼈 기준 지역 좌표라 뼈 위치와 함께 커진다)
    public static func scaled(_ m: Model3, _ k: Double) -> Model3 {
        m.mapValues { ps in ps.map { p in Prism(q: p.q.map { $0.map { $0 * k } }, mat: p.mat, tone: p.tone, part: p.part, c: p.c * k) } }
    }

