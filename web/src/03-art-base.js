const DK = { '!':'A', A:'a', a:'q', q:'1', '^':'B', B:'b', b:'p', '*':'S', S:'s', s:'z' };
const darker = rows => rows.map(r => r.replace(/[!AaqBb^*Ss]/g, c => DK[c]));
function roundShield(){
  const rows=[]; const r=6.3;
  for(let y=0;y<13;y++){ let s='';
    for(let x=0;x<13;x++){ const dx=x-6, dy=y-6, d=Math.hypot(dx,dy);
      if(d>r) s+='.'; else if(d>r-1.1) s+=(dx+dy<-3?'S':'z'); else if(d<1.5) s+=(dx+dy<0?'*':'s');
      else if(d<2.3) s+='v'; else s+=(x%3===1?'v':(dx+dy<-3?'W':'w')); }
    rows.push(s); }
  return rows;
}
