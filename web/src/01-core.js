const hexRGB = h => [parseInt(h.slice(1,3),16), parseInt(h.slice(3,5),16), parseInt(h.slice(5,7),16)];
function tintPal(base, sh, ks, hi, kh){
  const S = hexRGB(sh), Hh = hexRGB(hi);
  return base.map(row => row.map((c, s) => {
    const t = s/(STEPS-1); let rgb = hexRGB(c);
    const a = ks*Math.pow(1-t,1.4), b = kh*Math.pow(t,1.6);
    rgb = rgb.map((v,i)=> v*(1-a) + S[i]*a);
    rgb = rgb.map((v,i)=> v*(1-b) + Hh[i]*b);
    return rgb.map(v=>Math.round(Math.max(0,Math.min(255,v))));
  }));
}
